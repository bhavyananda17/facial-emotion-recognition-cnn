"""Generate results/summary.md from the run_info.json files, so no number is typed by hand.

    python scripts/make_summary.py

Needs results/<dataset>/{paper,clean}/run_info.json for ck, rafdb and fer2013, and
(optionally) results/ck/multi_seed.md from scripts/summarize_seeds.py.
"""

import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATASETS = [("ck", "CK+"), ("rafdb", "RAF-DB"), ("fer2013", "FER2013")]
PAPER = {"ck": 95, "rafdb": 83, "fer2013": 64}


def run(dataset, protocol):
    return json.loads((ROOT / "results" / dataset / protocol / "run_info.json").read_text())


def ck_seed_stats():
    """Mean and std of paper/clean accuracy over all CK+ seed runs (headline seed 42 included)."""
    acc = {"paper": [], "clean": []}
    for proto in acc:
        for d in (ROOT / "results" / "ck").glob(f"{proto}*"):
            f = d / "run_info.json"
            if f.exists() and re.fullmatch(rf"{proto}(_seed\d+)?", d.name):
                acc[proto].append(json.loads(f.read_text())["metrics"]["test_accuracy"] * 100)
    return {k: (st.mean(v), st.stdev(v), len(v)) for k, v in acc.items() if len(v) > 1}


def main():
    rows, ck_extra = [], ck_seed_stats()
    for key, name in DATASETS:
        p, c = run(key, "paper"), run(key, "clean")
        pa, ca = p["metrics"]["test_accuracy"] * 100, c["metrics"]["test_accuracy"] * 100
        rows.append(dict(key=key, name=name, paper=PAPER[key], pa=pa, ca=ca, gap=pa - ca,
                         pf=p["metrics"]["macro_f1"], cf=c["metrics"]["macro_f1"],
                         pmin=p["training_time_seconds"] / 60, cmin=c["training_time_seconds"] / 60,
                         pep=p["epochs_run"], cep=c["epochs_run"], n=p["test_images"], mon=c["monitored_images"]))

    out = ["# Results summary", "",
           "Test accuracy of this reproduction against the paper (Raj and Demirkol, Scientific Reports 15:38940, 2025). "
           "Generated by `scripts/make_summary.py` from `results/*/*/run_info.json`; seed 42; Apple M5 Pro GPU.", "",
           "| Dataset | Paper reports | **Mine, paper protocol** | **Mine, clean protocol** | Paper minus clean | Macro-F1 (paper / clean) |",
           "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['name']} | {r['paper']}% | **{r['pa']:.1f}%** | **{r['ca']:.1f}%** | {r['gap']:+.1f} pts | "
                   f"{r['pf']:.3f} / {r['cf']:.3f} |")
    out += ["", "**Paper protocol** copies the official notebooks: early stopping and learning-rate reduction watch the "
            "*test set*. **Clean protocol** changes only that: they watch a stratified 10% slice held out from training, "
            "and the test set is used once at the end. Same model, seed, augmentation and training images.", "",
            "| Dataset | Test images | Clean validation slice | Epochs run (paper / clean) | Training time (paper / clean) |",
            "|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['name']} | {r['n']:,} | {r['mon']:,} | {r['pep']} / {r['cep']} | "
                   f"{r['pmin']:.1f} / {r['cmin']:.1f} min |")

    by = {r["key"]: r for r in rows}
    ck, ra, fe = by["ck"], by["rafdb"], by["fer2013"]
    out += ["", "## Do the numbers reproduce?", "",
            f"Yes. In the paper protocol the three results are within 1.3 points of the reported ones "
            f"(CK+ {ck['pa'] - ck['paper']:+.1f}, RAF-DB {ra['pa'] - ra['paper']:+.1f}, FER2013 {fe['pa'] - fe['paper']:+.1f}). "
            "The paper rounds to whole percentages and reports a single unseeded run, so differences of this size are expected.", "",
            "## Does using the test set for early stopping inflate the numbers?", "",
            f"Not measurably, on any of the three datasets. The paper-minus-clean gap is {ra['gap']:+.1f} points on RAF-DB "
            f"({int(round(abs(ra['gap']) / 100 * ra['n']))} images of {ra['n']:,}) and {fe['gap']:+.1f} on FER2013 "
            f"({int(round(abs(fe['gap']) / 100 * fe['n']))} images of {fe['n']:,}), with the clean run ahead on RAF-DB."]
    if ck_extra:
        pm, ps, n = ck_extra["paper"]
        cm, cs, _ = ck_extra["clean"]
        out.append(f"On CK+ the seed-42 gap is {ck['gap']:+.1f} points, but over {n} training seeds the means are "
                   f"{pm:.1f} ± {ps:.1f}% (paper) and {cm:.1f} ± {cs:.1f}% (clean): a gap of {pm - cm:+.1f} points, "
                   "smaller than the seed-to-seed spread (`results/ck/multi_seed.md`).")
    out += ["",
            "**Likely reason (a hypothesis, not tested):** the paper's `ReduceLROnPlateau(factor=0.001)` cuts the learning "
            "rate a thousand-fold at the first plateau (to 1e-6 around epoch 45), so the model barely changes afterwards. "
            "Selecting the best epoch with the test set only helps if epochs differ; here the late epochs are almost identical.", "",
            "**What this does and does not show.** The protocol is still methodologically unsound (the test set influences "
            "training), but on these models and datasets that did not change the reported accuracy by more than the "
            "noise. RAF-DB and FER2013 were run with a single seed, so differences under about a point should not be "
            "read as a direction.", "",
            "## Other problems that do matter", "",
            "- **Mislabelled per-class results in the original.** The notebooks' label lists for FER2013 and RAF-DB do not "
            "match Keras' folder order, so the paper's per-class confusion matrices, ROC curves and Table 4 are mislabelled "
            "(4 of 7 RAF-DB classes; Sad / Surprise / Neutral on FER2013). Confirmed against the paper's own Table 4 (README).",
            "- **CK+ near-duplicate frames.** 91% of CK+ test images have a sibling frame from the same sequence in training, "
            "so CK+ accuracy is optimistic under both protocols.",
            "- **Learning-rate factor 0.001** and an unused ExponentialDecay schedule (README, \"Differences from the original code\").",
            ""]
    (ROOT / "results" / "summary.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
